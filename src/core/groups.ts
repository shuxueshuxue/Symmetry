/** does a completely filled table satisfy the group axioms? (rows and columns are permutations, and associativity) */
export function isGroupTable(t: ArrayLike<number>, n: number): boolean {
  for (let a = 0; a < n; a++) {
    let rows = 0, cols = 0
    for (let b = 0; b < n; b++) {
      const x = t[a * n + b], y = t[b * n + a]
      if (x < 0 || x >= n || y < 0 || y >= n) return false
      rows |= 1 << x; cols |= 1 << y
    }
    if (rows !== (1 << n) - 1 || cols !== (1 << n) - 1) return false
  }
  for (let a = 0; a < n; a++) for (let b = 0; b < n; b++) {
    const ab = t[a * n + b]
    for (let c = 0; c < n; c++) if (t[ab * n + c] !== t[a * n + t[b * n + c]]) return false
  }
  return true
}

/** relabel: new label p[x] for old label x */
export function relabel(t: ArrayLike<number>, n: number, p: ArrayLike<number>): Int8Array {
  const out = new Int8Array(n * n).fill(-1)
  for (let a = 0; a < n; a++) for (let b = 0; b < n; b++) {
    const v = t[a * n + b]
    out[p[a] * n + p[b]] = v < 0 ? -1 : p[v]
  }
  return out
}
