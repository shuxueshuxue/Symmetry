// The catalogue: every group of order 2..20, built from its definition.
// A table is row-major: t[a * n + b] = a·b. Element 0 is always the identity here.

export type Table = Int8Array

export interface GroupInfo {
  id: string
  /** display name, e.g. "C₄" */
  name: string
  order: number
  table: Table
  abelian: boolean
}

function cyclic(n: number): Table {
  const t = new Int8Array(n * n)
  for (let a = 0; a < n; a++) for (let b = 0; b < n; b++) t[a * n + b] = (a + b) % n
  return t
}

function product(A: Table, B: Table): Table {
  const p = Math.round(Math.sqrt(A.length)), q = Math.round(Math.sqrt(B.length)), n = p * q
  const t = new Int8Array(n * n)
  for (let a = 0; a < n; a++) for (let b = 0; b < n; b++) {
    const a1 = Math.floor(a / q), a2 = a % q, b1 = Math.floor(b / q), b2 = b % q
    t[a * n + b] = A[a1 * p + b1] * q + B[a2 * q + b2]
  }
  return t
}

/** symmetries of a regular m-gon: r^i s^j with s r s = r^-1; element index i + m*j */
function dihedral(m: number): Table {
  const n = 2 * m, t = new Int8Array(n * n)
  for (let a = 0; a < n; a++) for (let b = 0; b < n; b++) {
    const i1 = a % m, j1 = Math.floor(a / m), i2 = b % m, j2 = Math.floor(b / m)
    const i = (i1 + (j1 ? m - i2 : i2)) % m
    t[a * n + b] = i + m * (j1 ^ j2)
  }
  return t
}

/** a^(2m) = 1, x^2 = a^m, x a x^-1 = a^-1; element a^i x^j has index i + 2m*j */
function dicyclic(m: number): Table {
  const k = 2 * m, n = 2 * k, t = new Int8Array(n * n)
  for (let a = 0; a < n; a++) for (let b = 0; b < n; b++) {
    const i1 = a % k, j1 = Math.floor(a / k), i2 = b % k, j2 = Math.floor(b / k)
    let i = i1 + (j1 ? k - i2 : i2), j = j1 + j2
    if (j === 2) { i += m; j = 0 }
    t[a * n + b] = (i % k) + k * j
  }
  return t
}

/** the group generated by some permutations, elements numbered in the order they are found */
function fromPermutations(gens: number[][]): Table {
  const key = (p: number[]) => p.join(',')
  const mul = (p: number[], q: number[]) => q.map((x) => p[x]) // p after q
  const id = gens[0].map((_, i) => i)
  const els = [id], index = new Map([[key(id), 0]])
  for (let i = 0; i < els.length; i++) for (const g of gens) {
    const x = mul(els[i], g)
    if (!index.has(key(x))) { index.set(key(x), els.length); els.push(x) }
  }
  const n = els.length, t = new Int8Array(n * n)
  for (let a = 0; a < n; a++) for (let b = 0; b < n; b++) t[a * n + b] = index.get(key(mul(els[a], els[b])))!
  return t
}

/**
 * N extended by a cyclic group of order k acting through the automorphism phi (given as where each element of N goes).
 * Element (x, j) has index x + |N|·j, and (x, i)(y, j) = (x · phiⁱ(y), i + j).
 */
function semidirect(N: Table, phi: (x: number) => number, k: number): Table {
  const m = Math.round(Math.sqrt(N.length)), n = m * k, t = new Int8Array(n * n)
  const power: number[][] = [[...Array(m).keys()]]
  for (let j = 1; j < k; j++) power.push(power[j - 1].map(phi))
  for (let a = 0; a < n; a++) for (let b = 0; b < n; b++) {
    const x = a % m, i = Math.floor(a / m), y = b % m, j = Math.floor(b / m)
    t[a * n + b] = N[x * m + power[i][y]] + m * ((i + j) % k)
  }
  return t
}

const C = cyclic
/** a^m = x^k = 1, x a x⁻¹ = a^r */
const metacyclic = (m: number, k: number, r: number) => semidirect(C(m), (i) => (i * r) % m, k)
const sub = (k: number) => String(k).split('').map((d) => '₀₁₂₃₄₅₆₇₈₉'[+d]).join('')

function entry(id: string, name: string, table: Table): GroupInfo {
  const n = Math.round(Math.sqrt(table.length))
  let abelian = true
  for (let a = 0; a < n && abelian; a++) for (let b = 0; b < a; b++) if (table[a * n + b] !== table[b * n + a]) { abelian = false; break }
  return { id, name, order: n, table, abelian }
}

